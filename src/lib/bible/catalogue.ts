// Indexes for fast, constant-time lookup
const booksById = new Map<string, BibleBook>();
const booksBySlug = new Map<string, BibleBook>();
const booksByOrder = new Map<number, BibleBook>();

for (const book of CATHOLIC_BIBLE_BOOKS) {
  booksById.set(book.id.toLowerCase(), book);
  booksBySlug.set(book.slug.toLowerCase(), book);
  booksByOrder.set(book.order, book);
}

export function getBookById(id: string): BibleBook | undefined {
  return booksById.get(id.toLowerCase());
}

export function getBookBySlug(slug: string): BibleBook | undefined {
  return booksBySlug.get(slug.toLowerCase());
}

export function getBookByOrder(order: number): BibleBook | undefined {
  return booksByOrder.get(order);
}

export function getOldTestamentBooks(): BibleBook[] {
  return CATHOLIC_BIBLE_BOOKS.filter((b) => b.testament === 'OT');
}

export function getNewTestamentBooks(): BibleBook[] {
  return CATHOLIC_BIBLE_BOOKS.filter((b) => b.testament === 'NT');
}

export function isValidChapter(bookIdOrSlug: string, chapter: number): boolean {
  const book = getBookById(bookIdOrSlug) || getBookBySlug(bookIdOrSlug);
  if (!book) return false;
  return Number.isInteger(chapter) && chapter >= 1 && chapter <= book.chapterCount;
}

export interface NavigationTarget {
  book: BibleBook;
  chapter: number;
}

export function getAdjacentChapters(
  bookId: string,
  chapter: number
): {
  previous: NavigationTarget | null;
  next: NavigationTarget | null;
} {
  const currentBook = getBookById(bookId) || getBookBySlug(bookId);
  if (!currentBook) {
    return { previous: null, next: null };
  }

  let previous: NavigationTarget | null = null;
  let next: NavigationTarget | null = null;

  // Previous
  if (chapter > 1) {
    previous = { book: currentBook, chapter: chapter - 1 };
  } else if (currentBook.order > 1) {
    const prevBook = getBookByOrder(currentBook.order - 1);
    if (prevBook) {
      previous = { book: prevBook, chapter: prevBook.chapterCount };
    }
  }

  // Next
  if (chapter < currentBook.chapterCount) {
    next = { book: currentBook, chapter: chapter + 1 };
  } else if (currentBook.order < 73) {
    const nextBook = getBookByOrder(currentBook.order + 1);
    if (nextBook) {
      next = { book: nextBook, chapter: 1 };
    }
  }

  return { previous, next };
}
